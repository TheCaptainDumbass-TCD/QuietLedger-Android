package com.quietwire.quietledger.data.backup

import android.content.Context
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import com.quietwire.quietledger.core.money.Frequency
import com.quietwire.quietledger.core.money.Money
import com.quietwire.quietledger.data.db.DatabaseHolder
import com.quietwire.quietledger.data.db.QuietLedgerDatabase
import com.quietwire.quietledger.data.model.DebtCategory
import com.quietwire.quietledger.data.model.ExpenseGroup
import com.quietwire.quietledger.data.model.RecurringExpenseCategory
import com.quietwire.quietledger.data.repository.DebtRepository
import com.quietwire.quietledger.data.repository.RecurringExpenseRepository
import com.quietwire.quietledger.domain.payoff.PayoffCalculator
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.test.runTest
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/**
 * Cross-implementation test: a file written by the Python converter, read by
 * the Kotlin app.
 *
 * `scripts/desktop-to-android.py` reimplements the backup envelope in Python so
 * desktop data can be moved across without the phone needing to understand
 * SQLite or Fernet. Two implementations of one binary format is exactly the
 * arrangement that drifts silently: a changed iteration count, a different
 * nonce length, or JSON field names that no longer match would all produce a
 * file that looks fine and cannot be restored.
 *
 * The fixture is generated by that script from synthetic desktop rows, and
 * committed. If this test fails after a change to either side, they have
 * diverged.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class DesktopImportTest {

    private lateinit var database: QuietLedgerDatabase
    private lateinit var backups: BackupRepository
    private lateinit var debts: DebtRepository
    private lateinit var expenses: RecurringExpenseRepository

    private val passphrase = "fixture passphrase"

    @Before
    fun setUp() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        database = Room.inMemoryDatabaseBuilder(context, QuietLedgerDatabase::class.java)
            .allowMainThreadQueries()
            .build()
        val holder = object : DatabaseHolder {
            override fun require() = database
        }
        backups = BackupRepository(holder, appVersion = "test")
        debts = DebtRepository(holder)
        expenses = RecurringExpenseRepository(holder)
    }

    @After
    fun tearDown() = database.close()

    private fun fixture() = checkNotNull(
        javaClass.classLoader?.getResourceAsStream("desktop-import-fixture.qlbk")
    ) { "fixture missing; regenerate with scripts/desktop-to-android.py" }

    @Test
    fun `a file written by the python converter restores`() = runTest {
        val summary = backups.import(fixture(), passphrase.toCharArray())

        assertEquals(3, summary.debts)
        assertEquals(3, summary.recurringExpenses)
        assertNotNull(summary.exportedAt)
    }

    @Test
    fun `the desktop split lands in the right tables`() = runTest {
        backups.import(fixture(), passphrase.toCharArray())

        // Credit, Vehicles and Back Taxes are debts on the desktop side.
        assertEquals(
            listOf("Sample Back Tax", "Sample Card", "Sample Loan"),
            debts.getOpen().map { it.name }.sorted()
        )
        // Utilities and Insurance are recurring expenses, which the desktop
        // keeps in the same table and separates with a hardcoded category list.
        assertEquals(
            listOf("Electric", "Renters Insurance", "Water & Sewer"),
            expenses.observeActive().first().map { it.name }.sorted()
        )
    }

    @Test
    fun `money arrives exact to the cent`() = runTest {
        backups.import(fixture(), passphrase.toCharArray())

        val card = debts.getOpen().single { it.name == "Sample Card" }
        assertEquals(Money.parseOrNull("1254.63"), card.currentBalance)
        assertEquals(Money.parseOrNull("158.00"), card.scheduledPayment)
        assertEquals(DebtCategory.CREDIT_CARD, card.category)
    }

    @Test
    fun `a weekly payment keeps its frequency rather than being flattened`() = runTest {
        backups.import(fixture(), passphrase.toCharArray())

        val loan = debts.getOpen().single { it.name == "Sample Loan" }
        assertEquals(Frequency.WEEKLY, loan.paymentFrequency)
        assertEquals(Money.parseOrNull("100.00"), loan.scheduledPayment)
        // 100 weekly is 433.33 a month, not the desktop's 400.
        assertEquals(Money.parseOrNull("433.33"), loan.monthlyPayment)
    }

    @Test
    fun `a desktop row using both payment fields is folded without losing money`() = runTest {
        backups.import(fixture(), passphrase.toCharArray())

        // The desktop allowed 10.00 weekly and 20.00 monthly on one record and
        // added them as weekly * 4 + monthly, giving 60.00. Android holds one
        // amount and one frequency, so the converter folds them using the real
        // 52/12 weeks per month: 43.33 + 20.00.
        val backTax = debts.getOpen().single { it.name == "Sample Back Tax" }
        assertEquals(Frequency.MONTHLY, backTax.paymentFrequency)
        assertEquals(Money.parseOrNull("63.33"), backTax.scheduledPayment)
        assertTrue(
            "the folded figure must exceed the desktop's understated 60.00",
            backTax.scheduledPayment > Money.parseOrNull("60.00")!!
        )
    }

    @Test
    fun `expense categories survive the guess made during conversion`() = runTest {
        backups.import(fixture(), passphrase.toCharArray())

        val byName = expenses.observeActive().first().associateBy { it.name }
        assertEquals(RecurringExpenseCategory.ELECTRIC, byName["Electric"]!!.category)
        // A combined bill reads as water rather than sewer.
        assertEquals(RecurringExpenseCategory.WATER, byName["Water & Sewer"]!!.category)
        assertEquals(
            RecurringExpenseCategory.RENTERS_INSURANCE,
            byName["Renters Insurance"]!!.category
        )
        assertEquals(ExpenseGroup.UTILITIES, byName["Electric"]!!.category.group)
    }

    @Test
    fun `imported expenses stay out of the payoff plan`() = runTest {
        backups.import(fixture(), passphrase.toCharArray())

        val plan = PayoffCalculator().project(debts.getOpen())

        // Three debts, and none of the utilities or insurance.
        assertEquals(3, plan.projections.size)
        assertTrue(
            plan.projections.none { it.debt.name in setOf("Electric", "Water & Sewer") }
        )
    }
}
