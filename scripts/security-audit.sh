#!/usr/bin/env bash
# Static security audit of a built APK, plus a dependency vulnerability check.
#
#   ./scripts/security-audit.sh [debug|release]
#
# What this covers, and why it is worth having even though MobSF exists:
#
#   - Exported components in the *merged* manifest. This is the one that catches
#     real surprises, because libraries add components you never wrote and
#     manifest merging is invisible in your own source.
#   - Permissions in the merged manifest, same reasoning.
#   - Security-relevant application flags: backup, debuggable, cleartext.
#   - Whether the APK accidentally bundles secrets, keystores or real data.
#   - Secret-shaped strings in the compiled dex.
#   - Known advisories against every resolved dependency, via the OSV database.
#
# It deliberately does not try to be a full scanner. See docs/security-audit.md
# for what MobSF adds on top and when it is worth the setup.

set -euo pipefail

BUILD_TYPE="${1:-release}"
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_DIR"

export JAVA_HOME="${JAVA_HOME:-/usr/lib/jvm/java-21-openjdk-amd64}"
APKANALYZER="$HOME/Android/sdk/cmdline-tools/latest/bin/apkanalyzer"
APK="app/build/outputs/apk/$BUILD_TYPE/app-$BUILD_TYPE.apk"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

findings=0
note() { echo "  $*"; }
problem() { echo "  PROBLEM: $*"; findings=$((findings + 1)); }

if [ ! -f "$APK" ]; then
    echo "No APK at $APK. Build it first:" >&2
    echo "  ./gradlew :app:assemble${BUILD_TYPE^}" >&2
    exit 1
fi

echo "Auditing $APK"
echo

"$APKANALYZER" manifest print "$APK" > "$WORK/manifest.xml" 2>/dev/null

echo "== Exported components =="
# Exported means reachable by other apps. Each one is attack surface unless it
# is permission-protected.
python3 - "$WORK/manifest.xml" << 'PY'
import re, sys
xml = open(sys.argv[1]).read()
blocks = re.findall(r'<(activity|service|receiver|provider)\b(.*?)(?:/>|>)', xml, re.S)
for kind, attrs in blocks:
    if 'android:exported="true"' not in attrs:
        continue
    name = (re.search(r'android:name="([^"]+)"', attrs) or [None, '?'])[1]
    perm = re.search(r'android:permission="([^"]+)"', attrs)
    if perm:
        print(f"  {kind}: {name}")
        print(f"      protected by {perm.group(1)}")
    elif 'MainActivity' in name:
        print(f"  {kind}: {name}")
        print(f"      launcher activity, expected")
    else:
        print(f"  REVIEW {kind}: {name}  (exported, no permission)")
PY
echo

echo "== Permissions =="
# Parsed, not grepped. apkanalyzer puts each attribute on its own line, so a
# line-based regex reported "none requested" while two permissions were present.
# A false negative in a security check is worse than having no check.
python3 - "$WORK/manifest.xml" << 'PYPERM'
import re, sys
xml = open(sys.argv[1]).read()
perms = sorted(set(re.findall(r'<uses-permission\b[^>]*?android:name="([^"]+)"', xml, re.S)))
if not perms:
    print("  none requested")
for p in perms:
    # This one is generated by AndroidX for internally registered receivers. It
    # is declared and used by the app itself and grants nothing to others.
    if p.endswith("DYNAMIC_RECEIVER_NOT_EXPORTED_PERMISSION"):
        print(f"  {p}")
        print("      self-declared by AndroidX, not a capability request")
    else:
        print(f"  {p}")
PYPERM
echo

echo "== Application flags =="
for flag in allowBackup debuggable usesCleartextTraffic networkSecurityConfig dataExtractionRules; do
    value=$(grep -oE "android:$flag=\"[^\"]*\"" "$WORK/manifest.xml" | head -1 | cut -d'"' -f2 || true)
    [ -z "$value" ] && value="(not set)"
    case "$flag:$value" in
        allowBackup:true) problem "allowBackup is true; app data can be extracted via adb backup" ;;
        debuggable:true)
            if [ "$BUILD_TYPE" = "release" ]; then problem "release build is debuggable"
            else note "debuggable: true (expected in a debug build)"; fi ;;
        usesCleartextTraffic:true) problem "cleartext traffic permitted" ;;
        *) note "$flag: $value" ;;
    esac
done
echo

echo "== Bundled files that should not ship =="
bad=$(unzip -l "$APK" | grep -iE "\.jks$|\.keystore$|\.pem$|\.p12$|id_rsa|local\.properties|keystore\.properties|\.csv$|\.qlbk$|\.ftbackup$" || true)
if [ -n "$bad" ]; then problem "sensitive files inside the APK:"; echo "$bad" | sed 's/^/      /'
else note "none"; fi
echo

echo "== Secret-shaped strings in the dex =="
secrets=$(unzip -p "$APK" 'classes*.dex' 2>/dev/null | strings \
    | grep -oE "AIza[0-9A-Za-z_-]{30,}|sk_live_[0-9A-Za-z]{20,}|ghp_[0-9A-Za-z]{30,}|AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----" \
    | sort -u || true)
if [ -n "$secrets" ]; then problem "possible hardcoded credentials:"; echo "$secrets" | sed 's/^/      /'
else note "none"; fi
echo

echo "== Dependency advisories (OSV) =="
./gradlew -q :app:dependencies --configuration "${BUILD_TYPE}RuntimeClasspath" > "$WORK/deps.txt" 2>/dev/null || {
    note "could not resolve the dependency tree, skipping"
    exit 0
}
python3 - "$WORK/deps.txt" << 'PY'
import json, re, sys, urllib.request

coords = {}
for line in open(sys.argv[1]):
    m = re.search(r'([a-zA-Z0-9._-]+):([a-zA-Z0-9._-]+):([0-9][a-zA-Z0-9._-]*)(\s*->\s*([0-9][a-zA-Z0-9._-]*))?', line)
    if m:
        g, n, v, _, resolved = m.groups()
        coords[f"{g}:{n}"] = resolved or v

queries = [{"package": {"name": k, "ecosystem": "Maven"}, "version": v}
           for k, v in sorted(coords.items())]
try:
    req = urllib.request.Request(
        "https://api.osv.dev/v1/querybatch",
        data=json.dumps({"queries": queries}).encode(),
        headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=90) as r:
        results = json.load(r)["results"]
except Exception as e:
    print(f"  could not reach OSV ({e}), skipping")
    raise SystemExit(0)

hits = [(q["package"]["name"], q["version"], [v["id"] for v in (res.get("vulns") or [])])
        for q, res in zip(queries, results) if res.get("vulns")]

print(f"  checked {len(queries)} resolved dependencies")
if not hits:
    print("  no known advisories")
else:
    for name, ver, ids in hits:
        print(f"  ADVISORY {name}:{ver}")
        for i in ids:
            print(f"      https://osv.dev/vulnerability/{i}")
    raise SystemExit(1)
PY
osv_status=$?
echo
if [ "$findings" -gt 0 ] || [ "$osv_status" -ne 0 ]; then
    echo "RESULT: issues found, see above"
    exit 1
fi
echo "RESULT: nothing flagged"
